"use strict";

var fs = require("fs");
var os = require("os");
var path = require("path");
var format = require("./story-format");

var root = path.join(__dirname, "..");
var storiesDir = path.join(root, "stories");
var imagesRoot = path.join(root, "images");
var outFile = path.join(root, "books.js");

function storyDirs() {
  if (!fs.existsSync(storiesDir)) return [];
  return fs.readdirSync(storiesDir)
    .filter(function (name) { return name !== "_template" && name[0] !== "."; })
    .map(function (name) { return path.join(storiesDir, name); })
    .filter(function (dir) { return fs.statSync(dir).isDirectory(); })
    .sort();
}

function writeBooks(books) {
  var body = books.map(function (book) {
    return "CATALOG.push(" + JSON.stringify(book) + ");";
  }).join("\n");
  var text = "/* Generated by tools/build-stories.js. Do not edit.\n   Ready stories only. Ramayana stays in catalog.js. */\n" +
    "(function () {\n" +
    (body ? body + "\n" : "") +
    "})();\n";
  fs.writeFileSync(outFile, text);
}

function copyImages(book, dir) {
  var dest = path.join(imagesRoot, book.id);
  fs.rmSync(dest, { recursive: true, force: true });
  fs.mkdirSync(dest, { recursive: true });
  book.pages.forEach(function (page) {
    var file = path.basename(page.image);
    fs.copyFileSync(path.join(dir, "images", file), path.join(dest, file));
  });
}

function clearImages(id) {
  fs.rmSync(path.join(imagesRoot, id), { recursive: true, force: true });
}

function build() {
  var compiled = [];
  var failed = false;
  storyDirs().forEach(function (dir) {
    var result = format.compileStory(dir);
    var name = path.basename(dir);
    if (result.errors.length) {
      console.error(name + ":");
      result.errors.forEach(function (err) { console.error("  " + err); });
      if (result.meta && result.meta.ready === true) failed = true;
      else console.error("  (ready is not true, so the shelf is unchanged)");
      return;
    }
    compiled.push({ dir: dir, book: result.book });
  });
  if (failed) {
    console.error("Shelf was not rewritten. Fix the ready story and run this again.");
    process.exit(1);
  }
  var ready = [];
  compiled.forEach(function (item) {
    if (!item.book.ready) {
      clearImages(item.book.id);
      console.log(path.basename(item.dir) + ": checked, " + item.book.pages.length + " pages, not on the shelf");
      return;
    }
    copyImages(item.book, item.dir);
    ready.push(item.book);
    console.log(path.basename(item.dir) + ": " + item.book.pages.length + " pages on the shelf");
  });
  ready.sort(function (a, b) { return a.id < b.id ? -1 : a.id > b.id ? 1 : 0; });
  writeBooks(ready);
  console.log(ready.length ? "books.js has " + ready.length + " added " + (ready.length === 1 ? "story" : "stories") : "books.js has no added stories. Ramayana stays the shelf.");
}

function minimalJpeg(w, h) {
  var sof = Buffer.alloc(19);
  sof[0] = 0xff;
  sof[1] = 0xc0;
  sof.writeUInt16BE(17, 2);
  sof[4] = 8;
  sof.writeUInt16BE(h, 5);
  sof.writeUInt16BE(w, 7);
  sof[9] = 3;
  sof[10] = 1;
  sof[11] = 0x11;
  sof[13] = 2;
  sof[14] = 0x11;
  sof[16] = 3;
  sof[17] = 0x11;
  return Buffer.concat([Buffer.from([0xff, 0xd8]), sof, Buffer.from([0xff, 0xd9])]);
}

function assertCheck(cond, msg) {
  if (!cond) {
    console.error("CHECK FAILED: " + msg);
    process.exit(1);
  }
}

function check() {
  var tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), "katha-"));
  var id = "sample";
  var dir = path.join(tempRoot, id);
  var img = path.join(dir, "images");
  fs.mkdirSync(img, { recursive: true });
  var md = [
    "# Sample",
    "",
    "## Opening",
    "",
    "आरंभ",
    "",
    "### The Gate",
    "",
    "द्वार",
    "",
    "#### 1. A First Page",
    "",
    "पहला पृष्ठ",
    "",
    "Picture: `gate.jpg`",
    "",
    "The gate stood open.",
    "",
    "Nobody ranked the road. The next page is simply the next page.",
    "",
    "That is the whole of the contract.",
    "",
    "द्वार खुला था।",
    "",
    "मार्ग की कोई श्रेणी नहीं। अगला पृष्ठ बस अगला पृष्ठ है।",
    "",
    "यही पूरा नियम है।"
  ].join("\n");
  fs.writeFileSync(path.join(dir, "book.md"), md);
  fs.writeFileSync(path.join(dir, "book.json"), JSON.stringify({
    id: id,
    ready: true,
    titles: { en: "Sample", hi: "नमूना" },
    copy: {
      en: { note: "A sample.", doneTitle: "End", doneBody: "It stops." },
      hi: { note: "एक नमूना।", doneTitle: "अंत", doneBody: "यहीं रुकता है।" }
    }
  }));
  fs.writeFileSync(path.join(img, "gate.jpg"), minimalJpeg(864, 1152));
  var good = format.compileStory(dir);
  assertCheck(!good.errors.length, good.errors.join("; "));
  assertCheck(good.book.pages.length === 1, "one page");
  assertCheck(good.book.pages[0].image === id + "/gate.jpg", "image path");
  assertCheck(good.book.pages[0].text.hi.title === "पहला पृष्ठ", "hindi title");
  assertCheck(good.book.pages[0].text.en.hook === "The gate stood open.", "hook");
  assertCheck(!good.book.pages[0].text.te, "missing language stays absent");

  fs.writeFileSync(path.join(img, "gate.jpg"), minimalJpeg(400, 300));
  var badSize = format.compileStory(dir);
  assertCheck(badSize.errors.some(function (e) { return e.indexOf("864x1152") !== -1; }), "size error");

  fs.writeFileSync(path.join(img, "gate.jpg"), minimalJpeg(864, 1152));
  fs.writeFileSync(path.join(dir, "book.md"), md + "\n\n#### 2. Second\n\nदूसरा\n\nPicture: `gate.jpg`\n\nAgain the gate.\n\nSame road.\n\nStill no ranking.\n\nफिर द्वार।\n\nवही मार्ग।\n\nअब भी कोई श्रेणी नहीं।\n");
  var dup = format.compileStory(dir);
  assertCheck(dup.errors.some(function (e) { return e.indexOf("already used") !== -1; }), "duplicate picture");

  fs.writeFileSync(path.join(dir, "book.json"), JSON.stringify({
    id: id, ready: true, rank: 1,
    titles: { en: "Sample", hi: "नमूना" },
    copy: {
      en: { note: "A sample.", doneTitle: "End", doneBody: "It stops." },
      hi: { note: "एक नमूना।", doneTitle: "अंत", doneBody: "यहीं रुकता है।" }
    }
  }));
  var banned = format.compileStory(dir);
  assertCheck(banned.errors.some(function (e) { return e.indexOf("rank") !== -1; }), "no rank field");

  fs.rmSync(tempRoot, { recursive: true, force: true });
  console.log("story format checks passed");
}

if (process.argv.indexOf("--check") !== -1) check();
else build();
